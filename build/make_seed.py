# -*- coding: utf-8 -*-
"""Writes supabase/seed.sql from build/data/defaults.json (the current site content).
Run:  python3 build/make_seed.py
Existing rows are never overwritten (ON CONFLICT DO NOTHING)."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
D = json.load(open(os.path.join(HERE, 'data', 'defaults.json'), encoding='utf-8'))


def q(v):
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (list, dict)):
        return q(json.dumps(v, ensure_ascii=False)) + '::jsonb'
    s = str(v)
    tag = '$amw$'
    assert tag not in s
    return f'{tag}{s}{tag}'


out = ['-- =====================================================================',
       '-- AMweb: initial content (prices + Conseils articles), generated by build/make_seed.py',
       '-- Run ONCE after schema.sql. Existing rows are kept (ON CONFLICT DO NOTHING).',
       '-- =====================================================================', '']
for o in D['offres']:
    out.append(f"insert into public.offres (id, prix, duree_fr, duree_en, duree_ar) values ({q(o['id'])}, {q(o['prix'])}, {q(o['duree_fr'])}, {q(o['duree_en'])}, {q(o['duree_ar'])}) on conflict (id) do nothing;")
out.append('')
cols = ['slug', 'lang', 'ordre', 'titre_seo', 'h1', 'description', 'categorie', 'image', 'chapo', 'corps', 'faq', 'sources', 'mots_cles', 'publie', 'date_pub']
for a in D['articles']:
    vals = ', '.join(q(a[c]) for c in cols)
    out.append(f"insert into public.articles ({', '.join(cols)}) values ({vals}) on conflict (slug, lang) do nothing;")
for r in D.get('realisations', []):
    pass  # none yet
path = os.path.join(os.path.dirname(HERE), 'supabase', 'seed.sql')
open(path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote', path, len(D['articles']), 'articles')
